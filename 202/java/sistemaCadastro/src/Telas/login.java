    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String nome = "Pedro";
        String senha = "0123ph";
        String nomeDigitado = txtNome.getText();
        String senhaDigitada = txtSenha.getText();
        
        if(nomeDigitado.isEmpty() || senhaDigitada.isEmpty()){
            JOptionPane.showMessageDialog(this, "Por favor, digite o usuário e a senha!");
        }else if(!nomeDigitado.equals(nome) || !senhaDigitada.equals(senha)){
             JOptionPane.showMessageDialog(this, "A senha ou o nome de usuário estão incorretos!");
        }else if(nomeDigitado.equals(nome) && senhaDigitada.equals(senha)){
            JOptionPane.showMessageDialog(this, "Seja bem-vindo(a), " + nome + "!");
            telaPrincipal principal = new telaPrincipal();
                //"Maximize a janela principal ocupando toda a área disponível da tela."
                principal.setExtendedState(JFrame.MAXIMIZED_BOTH);
                principal.setVisible(true);
                this.dispose();
        }else{
            JOptionPane.showMessageDialog(this, "Acesso negado.");
        }
    }//GEN-LAST:event_jButton2ActionPerformed

